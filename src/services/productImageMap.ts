/**
 * Resolves the authentic compressed product image URL for a given product slug, category, or name.
 * Falls back to category banner or null (triggering branded emblem placeholder).
 */
export function getProductImage(
  slug?: string | null,
  category?: string | null,
  name?: string | null
): string | null {
  if (slug && PRODUCT_IMAGE_MAP[slug]) {
    return PRODUCT_IMAGE_MAP[slug];
  }

  // Name-based fuzzy lookup against authoritative catalog map
  if (name) {
    const norm = String(name)
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/(^-|-$)/g, '');
    if (PRODUCT_IMAGE_MAP[norm]) {
      return PRODUCT_IMAGE_MAP[norm];
    }
    for (const [key, url] of Object.entries(PRODUCT_IMAGE_MAP)) {
      if (key.includes(norm) || norm.includes(key.replace(/^thin-crust-pizza-|^burgers-|^sandwiches-/, ''))) {
        return url;
      }
    }
  }

  // Category fallback with plural/singular normalization
  if (category) {
    const normCategory = category === 'pizzas' ? 'thin-crust-pizza' : category;
    return `/images/categories/${normCategory}.jpg`;
  }
  return null;
}

/**
 * Universal product image resolver that safely inspects any product object
 * (whether from Supabase, local catalog, or cart snapshot) and returns
 * the authentic photo URL.
 */
export function resolveProductImage(product?: any): string | null {
  if (!product) return null;

  // 1. Valid non-empty image string
  const directImage = [product.image, product.imageUrl, product.image_url].find(
    (img) => typeof img === 'string' && img.trim() && img.trim() !== 'null'
  );
  if (directImage) {
    return directImage.trim();
  }

  // 2. Direct slug or ID lookup
  const identifier = product.slug || product.id;
  if (identifier && PRODUCT_IMAGE_MAP[identifier]) {
    return PRODUCT_IMAGE_MAP[identifier];
  }

  // 3. Name or Category-based lookup
  const category = product.category || product.categoryId || product.category_id;
  const imageFromCatalog = getProductImage(identifier, category, product.name);
  if (imageFromCatalog) {
    return imageFromCatalog;
  }

  return null;
}

